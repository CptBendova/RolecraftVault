const assert=require("assert"),crypto=require("crypto"),C=require("../app/vault-sync-core");
const hash=async s=>crypto.createHash("sha256").update(s).digest("hex");
const item=(id,name)=>({id,name,images:[]}), key=id=>C.keyOf("lore",id);
const table=rows=>Object.fromEntries(rows.map(r=>[key(r.id),r]));
(async()=>{
  const tablet=await C.scan(table([item("same","Tablet version"),item("tablet","Tablet only")]),null,"tablet",hash);
  const pc=await C.scan(table([item("same","Computer version"),item("pc","Computer only")]),null,"computer",hash);
  const phone=await C.scan(table([item("phone","Phone only")]),null,"phone",hash);
  const pc2=await C.scan(table([item("pc2","Second computer")]),null,"computer2",hash);
  const first=await C.merge([tablet,pc,phone,pc2],"tablet",hash),reverse=await C.merge([pc2,phone,pc,tablet],"tablet",hash);
  assert.equal(C.canonical(first),C.canonical(reverse));
  assert.equal(first.items[key("same")].name,"Tablet version");
  assert.equal(Object.keys(first.items).length,6);
  assert(Object.values(first.items).some(v=>v.name==="Computer version (sync conflict)"));
  console.log("PASS four different libraries converge without losing unique records or conflicting writing");
  const newest=item("preferred","Primary's writing"),newestHash=await hash(C.canonical(newest));let other;
  for(let n=0;n<1000;n++){other=item("preferred","Older writing "+n);if(await hash(C.canonical(other))<newestHash)break;}
  const initial=await Promise.all([["zz-primary",newest],["aa-phone",newest],["pc",other]].map(([device,value])=>C.scan(table([value]),null,device,hash)));
  const preferred=await C.merge(initial,"zz-primary",hash);
  assert.equal(preferred.items[key("preferred")].name,newest.name);
  console.log("PASS identical copies on another device cannot displace the selected primary's initial version");
  const saved=await C.scan(first.items,first.snapshot,"tablet",hash);
  const again=await C.merge([saved,pc,tablet,phone,pc2],"tablet",hash);
  assert.equal(C.canonical(again.items),C.canonical(first.items));
  assert.equal(Object.keys(again.items).length,6);
  console.log("PASS retries and stale peers do not multiply conflict copies");
  const changed={...first.items,[key("same")]:item("same","New writing on phone")};
  const descendant=await C.scan(changed,saved,"phone",hash);
  const next=await C.merge([descendant,saved],"tablet",hash);
  assert.equal(next.items[key("same")].name,"New writing on phone");
  console.log("PASS later edits on a non-primary device supersede their observed ancestors");
  const deleted={...changed};delete deleted[key("same")];
  const tombstone=await C.scan(deleted,descendant,"computer",hash);
  const removed=await C.merge([tombstone,descendant],"tablet",hash);
  assert(!removed.items[key("same")]);
  const offline=await C.scan({...changed,[key("same")]:item("same","Offline edit")},descendant,"computer2",hash);
  const concurrent=await C.merge([offline,tombstone],"tablet",hash);
  assert.equal(concurrent.items[key("same")].name,"Offline edit");
  console.log("PASS known deletions converge, but concurrent writing is never erased by a deletion");
  const damaged=JSON.parse(JSON.stringify(tablet));damaged.entries[key("same")].versions[0].value.name="Tampered";
  await assert.rejects(C.validate(damaged,hash),/checksum/);
  assert.throws(()=>C.collect({"lore:all":JSON.stringify([item("duplicate","a"),item("duplicate","b")])}),/Duplicate/);
  assert.throws(()=>C.keyOf("lore","__proto__"));
  assert.equal(C.canonical(C.collect(C.expand(first.items))),C.canonical(first.items));
  const privatePictures=C.collect({blurset:JSON.stringify(["portrait"])});
  assert.deepEqual(JSON.parse(C.expand(privatePictures).blurset),["portrait"]);
  const order=C.expand(table([item("a","A"),item("z","Z")]),{"lore:all":JSON.stringify([item("z","Z"),item("a","A")])});
  assert.deepEqual(JSON.parse(order["lore:all"]).map(r=>r.id),["z","a"]);
  console.log("PASS picture privacy marks sync and incoming edits preserve this device's existing record order");
  console.log("PASS checksums, identity validation and storage round-trips enforce the merge boundary");
})().catch(e=>{console.error(e);process.exitCode=1;});
